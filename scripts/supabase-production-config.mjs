// Writes the COMMITTED production browser config
// src/app/data/supabase-production-config.js (read by production-accounts.js
// only when PRODUCTION_SUPABASE_ACCOUNTS is on) from the untracked
// .env.supabase.production.local, so the key never has to be pasted into
// chat or a terminal. The project URL is derived from
// PRODUCTION_PROJECT_REF (supabase-env.js); only a PUBLISHABLE key
// (sb_publishable_…) is accepted — a secret, service_role or legacy JWT key
// is refused, as is any config for the test project. The key is never
// printed.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { checkEnvConfig, PRODUCTION_PROJECT_REF } from "../src/app/data/supabase-env.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : null; };
const envPath = arg("--env") || join(root, ".env.supabase.production.local");          // --env / --out: for the tests
const outPath = arg("--out") || join(root, "src", "app", "data", "supabase-production-config.js");

if (!existsSync(envPath)) {
    console.error("Missing .env.supabase.production.local — copy .env.supabase.production.example to it and fill in the publishable key.");
    process.exit(1);
}
const env = {};
for (const line of readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith("#")) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}
const key = env.SUPABASE_PRODUCTION_PUBLISHABLE_KEY || "";
if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(key)) {
    console.error("Not written: SUPABASE_PRODUCTION_PUBLISHABLE_KEY must be a publishable key (sb_publishable_…).");
    process.exit(1);
}
const config = { url: `https://${PRODUCTION_PROJECT_REF}.supabase.co`, publishableKey: key };
const check = checkEnvConfig("production", config);
if (!check.ok) {
    console.error(`Not written: ${check.reason}`);
    process.exit(1);
}
writeFileSync(outPath,
    "// swimtics-production — PUBLIC browser config (project URL + publishable key only).\n" +
    "// Generated by scripts/supabase-production-config.mjs. Read by production-accounts.js\n" +
    "// only while PRODUCTION_SUPABASE_ACCOUNTS is on (it is off), and only on\n" +
    "// swimtics.com / www.swimtics.com. Never put a secret or service_role key here.\n" +
    `export default ${JSON.stringify(config, null, 4)};\n`);
console.log(`Wrote ${outPath.replace(root, ".")} for ${new URL(config.url).hostname} (publishable key, not shown).`);
