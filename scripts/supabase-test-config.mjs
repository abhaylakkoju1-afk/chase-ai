// Turns the untracked .env.supabase.local into the untracked browser config
// src/app/data/supabase-config.local.js used by Supabase test mode
// (http://127.0.0.1:4173/?supabase). Only the project URL and the
// publishable key are written; a secret or service_role key is refused.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { checkPublicConfig } from "../src/app/data/supabase-test-core.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env.supabase.local");
const outPath = join(root, "src", "app", "data", "supabase-config.local.js");

if (!existsSync(envPath)) {
    console.error("Missing .env.supabase.local — copy .env.supabase.example to it and fill in the two values.");
    process.exit(1);
}
const env = {};
for (const line of readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith("#")) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}
const config = { url: (env.SUPABASE_URL || "").replace(/\/+$/, ""), publishableKey: env.SUPABASE_PUBLISHABLE_KEY || "" };
const check = checkPublicConfig(config);
if (!check.ok) {
    console.error(`Not written: ${check.reason}`);
    process.exit(1);
}
writeFileSync(outPath,
    "// Generated by scripts/supabase-test-config.mjs from .env.supabase.local.\n" +
    "// Git-ignored. Test project only; publishable key only.\n" +
    `export default ${JSON.stringify(config, null, 4)};\n`);
console.log(`Wrote ${outPath.replace(root, ".")} for ${new URL(config.url).hostname} (publishable key; not committed).`);
